'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const src=fs.readFileSync(require('node:path').resolve(__dirname,'../sw.js'),'utf8');
let tests=0;const ok=(condition,msg)=>{assert.ok(condition,msg);tests++};
const listeners={},store=new Map(),removed=[],responds=[];
const urls=['index.html','manifest.json','icons/icon-192.png','icons/icon-512.png'].map(x=>'https://example.org/cards/'+x);
const caches={async open(name){if(!store.has(name))store.set(name,new Map());const m=store.get(name);return {async addAll(reqs){for(const r of reqs)m.set(r.url,new Response('cached'))},async match(req){return m.get(req.url)}}},async keys(){return [...store.keys()]},async delete(key){removed.push(key);return store.delete(key)}};
store.set('credit-card-usage-static-v0.3.1',new Map());
let skipped=false,claimed=false,externalFetches=0;
const context={caches,Request,Response,URL,self:{registration:{scope:'https://example.org/cards/'},addEventListener(type,cb){listeners[type]=cb},skipWaiting:async()=>{skipped=true},clients:{claim:async()=>{claimed=true}}},fetch:async()=>{externalFetches++;return new Response('fetched')}};
vm.createContext(context);vm.runInContext(src,context);
const wait=async(event,props={})=>{let p;listeners[event]({...props,waitUntil(x){p=x},respondWith(x){p=x}});return p&&await p};
(async()=>{
 await wait('install');
 ok(store.has('credit-card-usage-static-v0.3.4'),'new cache');
 ok(store.get('credit-card-usage-static-v0.3.4').size===4,'4 app-shell assets');
 ok(skipped,'skipwaiting');
 await wait('activate');
 ok(removed.includes('credit-card-usage-static-v0.3.1'),'removed prior cache');
 ok(claimed,'clients.claim');
 const offline=await wait('fetch',{request:new Request(urls[0])});
 ok(await offline.text()==='cached','cache response offline');
 const external=await wait('fetch',{request:new Request('https://accounts.google.com/gsi/client')});
 ok(external===undefined,'google script not cached/intercepted');
 const api=await wait('fetch',{request:new Request('https://www.googleapis.com/drive/v3/about')});
 ok(api===undefined,'drive API not intercepted');
 const write=await wait('fetch',{request:new Request(urls[0],{method:'POST'})});
 ok(write===undefined,'POST not intercepted');
 ok(externalFetches===0,'SW does not make network on non-assets');
 console.log('PASS '+tests+' Service Worker checks');
})().catch(e=>{console.error(e);process.exitCode=1});
